CREATE TABLE app_users (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6) with time zone NOT NULL,
    email       varchar(120) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL
);

CREATE TABLE user_settings (
    user_id                       bigint PRIMARY KEY REFERENCES app_users(id),
    open_ai_key_encrypted         text,
    ai_provider                   varchar(255),
    open_ai_model                 varchar(255),
    strava_ftp                    integer,
    strava_client_id_encrypted    text,
    strava_client_secret_encrypted text
);

CREATE TABLE strava_tokens (
    user_id                 bigint PRIMARY KEY REFERENCES app_users(id),
    access_token_encrypted  text NOT NULL,
    refresh_token_encrypted text NOT NULL,
    expires_at              timestamp(6) with time zone NOT NULL,
    strava_athlete_id       bigint UNIQUE
);

CREATE TABLE activities (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 bigint NOT NULL REFERENCES app_users(id),
    strava_activity_id      bigint NOT NULL,
    name                    varchar(255),
    description             text,
    activity_type           varchar(255),
    sport_type              varchar(255),
    activity_date           date,
    start_date_local        timestamp(6) without time zone,
    distance_km             double precision NOT NULL,
    moving_time_min         integer NOT NULL,
    elapsed_time_min        integer NOT NULL,
    elevation_gainm         double precision NOT NULL,
    elevation_highm         double precision,
    elevation_lowm          double precision,
    average_speed_kph       double precision,
    max_speed_kph           double precision,
    average_cadence         double precision,
    average_watts           double precision,
    weighted_average_watts  double precision,
    max_watts               integer,
    kilojoules              double precision,
    average_heart_rate      double precision,
    max_heart_rate          double precision,
    calories                double precision,
    average_temperaturec    double precision,
    perceived_exertion      integer,
    suffer_score            integer,
    workout_type            integer,
    device_name             varchar(255),
    device_watts            boolean,
    trainer                 boolean NOT NULL,
    commute                 boolean NOT NULL,
    manual                  boolean NOT NULL,
    analyzed                boolean NOT NULL,
    UNIQUE (user_id, strava_activity_id)
);

CREATE TABLE generated_workouts (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint NOT NULL REFERENCES app_users(id),
    name         varchar(255),
    planned_date date,
    zwo_content  text,
    created_at   timestamp(6) with time zone NOT NULL,
    deleted      boolean NOT NULL DEFAULT false
);

CREATE TABLE ai_prompts (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL REFERENCES app_users(id),
    prompt     text NOT NULL,
    created_at timestamp(6) with time zone NOT NULL
);

CREATE TABLE user_events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint NOT NULL REFERENCES app_users(id),
    type        varchar(32) NOT NULL,
    description varchar(240) NOT NULL,
    created_at  timestamp(6) with time zone NOT NULL
);
